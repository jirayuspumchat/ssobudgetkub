NORM_DROP = re.compile(r'[\s\u200b"\'()\[\],./\-–—:;]+')


def normalise(name):
    s = re.sub(r'^\d+(\.\d+)*\.?\s*', '', name)          # drop the printed item number
    s = re.sub(r'(พ\.ศ\.|ประจำปี|ปี)\s*25\d\d(\s*[-–]\s*25\d\d)?', ' ', s)
    s = NORM_DROP.sub('', s)
    return s


SIMILAR_MIN = 0.93


def project_year_mapping():
    """One รหัสกลาง per exact normalised name. Similar-but-not-identical names are
    reported as a candidate to review, never merged - "ค่าจ้างเหมารักษาความปลอดภัย"
    and "ค่าจ้างเหมารักษาความสะอาด" are 0.95 similar and are different items."""
    items = {yr: [r for r in BUD[yr] if r['kind'] == 'item'] for yr in sorted(BUD)}
    key_years, key_names = collections.defaultdict(set), {}
    for yr, rs in items.items():
        for r in rs:
            k = normalise(r['label'])
            key_years[k].add(yr)
            plain = re.sub(r'^\d+(\.\d+)*\.?\s*', '', r['label']).strip()
            if k not in key_names or yr >= key_names[k][0]:
                key_names[k] = (yr, plain)

    keys = sorted(key_years)
    code = {k: 'ITM-%04d' % i for i, k in enumerate(keys, 1)}

    # nearest neighbour among the keys that appear in a different set of years
    near = {}
    for a, ka in enumerate(keys):
        best = None
        for kb in keys:
            if kb == ka or abs(len(ka) - len(kb)) > max(8, len(ka) * 0.15):
                continue
            if key_years[kb] & key_years[ka]:
                continue                      # same year: a sibling line, not a rename
            ratio = difflib.SequenceMatcher(None, ka, kb).ratio()
            if ratio >= SIMILAR_MIN and (best is None or ratio > best[0]):
                best = (ratio, kb)
        if best:
            near[ka] = best

    rows = []
    for yr in sorted(items):
        doc, fn, rdate, rthai = BUD_SRC[yr]
        for i, r in enumerate(BUD[yr]):
            if r['kind'] != 'item':
                continue
            k = normalise(r['label'])
            yrs = sorted(key_years[k])
            sim = near.get(k)
            status = ('พบปีเดียวและมีรายการชื่อคล้ายกันในปีอื่น ต้องตรวจสอบด้วยคน' if sim and len(yrs) == 1 else
                      'ชื่อตรงกันข้ามปี และยังมีรายการชื่อคล้ายกันให้ตรวจเพิ่ม' if sim else
                      'พบปีเดียว ยังไม่ยืนยันการจับคู่ข้ามปี' if len(yrs) == 1 else
                      'จับคู่อัตโนมัติด้วยชื่อตรงกัน')
            rows.append([code[k], key_names[k][1], r['label'], yr, len(yrs), ' | '.join(yrs),
                         'ชื่อตรงกันทุกตัวอักษรหลังปรับรูป', status,
                         code[sim[1]] if sim else '', key_names[sim[1]][1] if sim else '',
                         round(sim[0] * 100, 1) if sim else '',
                         ' | '.join(sorted(key_years[sim[1]])) if sim else '',
                         n2(r['alloc']), n2(r['spent']),
                         '%s-%04d' % (yr, i + 1), doc, fn, r['page']])
    w('project_year_mapping.csv',
      ['รหัสกลาง', 'ชื่อมาตรฐาน', 'ชื่อรายการเดิมตามเอกสาร', 'ปีงบประมาณ', 'จำนวนปีที่พบ',
       'ปีที่พบทั้งหมด', 'วิธีจับคู่', 'สถานะตรวจสอบการจับคู่', 'รหัสกลางที่อาจเป็นรายการเดียวกัน',
       'ชื่อที่อาจเป็นรายการเดียวกัน', 'ค่าความคล้าย_ร้อยละ', 'ปีของรายการที่อาจเป็นรายการเดียวกัน',
       'จัดสรร', 'รวมเบิกจ่ายและผูกพัน', 'รหัสแถวใน_budget_items', 'รหัสเอกสาร',
       'ไฟล์ต้นทาง', 'หน้าอ้างอิง'], rows)
    return rows


