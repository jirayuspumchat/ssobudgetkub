def data_dictionary():
    """Runs last: it reads the header of every file that has already been written."""
    override = {(f, c): (m, t, u, d) for f, c, m, t, u, d in DICT_ROWS}
    rows = []
    for name in sorted(os.listdir(OUT)):
        if not name.endswith('.csv'):
            continue
        if name == 'data_dictionary.csv':
            header = DICT_HEADER
        else:
            with open(os.path.join(OUT, name), encoding='utf-8-sig', newline='') as fh:
                header = next(csv.reader(fh))
        for col in header:
            meta = override.get((name, col)) or COMMON.get(col)
            if meta is None:
                meta = ('คอลัมน์ในไฟล์ %s' % name, 'ข้อความ', '-', 'สร้างจากข้อมูลที่สกัดได้')
            rows.append([name, col] + list(meta))
    w('data_dictionary.csv',
      DICT_HEADER, rows)


