def w(name, header, rows):
    path = os.path.join(OUT, name)
    with open(path, 'w', encoding='utf-8-sig', newline='') as fh:
        cw = csv.writer(fh)
        cw.writerow(header)
        cw.writerows(rows)
    print('%-36s %6d rows' % (name, len(rows)))


def n2(v):
    return '' if v is None else round(v, 2)


def thai_to_iso(d):
    """'01.06.2563' -> '2563-06-01' (kept in the Buddhist era, as printed)."""
    dd, mm, yy = d.split('.')
    return '%s-%s-%s' % (yy, mm, dd)


def greg(d):
    dd, mm, yy = (int(x) for x in d.split('.'))
    return datetime.date(yy - 543, mm, dd)


