def organization_units():
    rows = []
    org = [s for s in SUB if s['kind'] == 'org'][0]
    tot = [sum(d[k] for d in DET) for k in ('acq', 'dep', 'nbv')]
    rows.append(['หน่วยงาน', org['code'], org['name'], '', '', len(DET),
                 len(set(d['asset_id'] for d in DET)), n2(tot[0]), n2(tot[1]), n2(tot[2]),
                 'รากของโครงสร้าง', ASSET_DOC, ASSET_FILE, org['page']])

    area = collections.defaultdict(lambda: [0.0, 0.0, 0.0, 0, set(), set()])
    cc = collections.defaultdict(lambda: [0.0, 0.0, 0.0, 0, set(), set()])
    for d in DET:
        for key, bag in (((d['area'], d['area_name']), area), ((d['cost_center'], d['cost_center_name']), cc)):
            c = bag[key]
            c[0] += d['acq']; c[1] += d['dep']; c[2] += d['nbv']; c[3] += 1
            c[4].add(d['asset_id'])
            c[5].add(d['area'] if bag is cc else d['cost_center'])
    pages = collections.defaultdict(set)                 # code -> pages carrying its subtotal
    for s in SUB:
        pages[(s['kind'], s['code'])].add(s['page'])

    def pg(kind, code):
        return '; '.join(str(p) for p in sorted(pages[(kind, code)])[:6])

    for k in sorted(area):
        v = area[k]
        rows.append(['พื้นที่', k[0], k[1], org['code'], org['name'], v[3], len(v[4]),
                     n2(v[0]), n2(v[1]), n2(v[2]),
                     'อยู่ใต้หน่วยงาน %s และมีศูนย์ต้นทุน %d แห่ง' % (org['code'], len(v[5])),
                     ASSET_DOC, ASSET_FILE, pg('area', k[0])])
    for k in sorted(cc):
        v = cc[k]
        areas = sorted(v[5])
        nm = {a: n for (a, n) in area}
        rows.append(['ศูนย์ต้นทุน', k[0], k[1], areas[0], nm.get(areas[0], ''), v[3], len(v[4]),
                     n2(v[0]), n2(v[1]), n2(v[2]),
                     'ผูกกับพื้นที่เดียวในเอกสาร' if len(areas) == 1
                     else 'พบมากกว่าหนึ่งพื้นที่ ต้องตรวจสอบ',
                     ASSET_DOC, ASSET_FILE, pg('cost_center', k[0])])
    w('organization_units.csv',
      ['ประเภทรหัส', 'รหัส', 'ชื่อหน่วยงาน', 'รหัสหน่วยเหนือ', 'ชื่อหน่วยเหนือ',
       'จำนวนรายการย่อยสินทรัพย์', 'จำนวนรหัสสินทรัพย์', 'มูลค่าการได้มา', 'ค่าเสื่อมราคาสะสม',
       'มูลค่าตามบัญชี', 'ความสัมพันธ์ที่ตรวจสอบได้', 'รหัสเอกสาร', 'ไฟล์ต้นทาง', 'หน้าอ้างอิง'], rows)
